"""Create small SYNTHETIC demo MIDI files so you can try the pipeline immediately.

These files are generated by a simple random program, so they contain no
copyrighted music. They are only meant for testing: for good-sounding results
use a larger, legally obtained MIDI dataset (see README).

    python -m src.sample_data
    python -m src.sample_data --files 20 --length 300
"""

from __future__ import annotations

import argparse
import sys

import numpy as np

from src import config
from src.midi_utils import pitches_to_token, tokens_to_stream, write_midi_file
from src.utils import MusicGenError, PathLike, setup_logging

MAJOR_SCALE = (0, 2, 4, 5, 7, 9, 11)
MINOR_SCALE = (0, 2, 3, 5, 7, 8, 10)


def make_demo_tokens(length: int, rng: np.random.Generator) -> list[str]:
    """Build a melody from a repeating motif with small variations and some chords."""
    root = int(rng.choice([55, 57, 60, 62, 64]))
    scale = MAJOR_SCALE if rng.random() < 0.6 else MINOR_SCALE
    scale_notes = [root + 12 * octave + step for octave in range(2) for step in scale]
    motif = [int(rng.integers(0, len(scale_notes))) for _ in range(8)]

    tokens: list[str] = []
    while len(tokens) < length:
        for degree in motif:
            degree = int(np.clip(degree + rng.choice([0, 0, 0, 1, -1]), 0, len(scale_notes) - 1))
            if rng.random() < 0.15 and degree + 4 < len(scale_notes):
                tokens.append(pitches_to_token([scale_notes[degree], scale_notes[degree + 2], scale_notes[degree + 4]]))
            else:
                tokens.append(pitches_to_token([scale_notes[degree]]))
        if rng.random() < 0.3:
            motif = [int(np.clip(d + rng.choice([-1, 0, 1]), 0, len(scale_notes) - 1)) for d in motif]
    return tokens[:length]


def create_sample_dataset(
    output_dir: PathLike = config.RAW_DATA_DIR, files: int = 12, length: int = 240, seed: int = 42
) -> list[str]:
    """Write `files` synthetic MIDI files and return their paths."""
    rng = np.random.default_rng(seed)
    created: list[str] = []
    for index in range(1, files + 1):
        tokens = make_demo_tokens(length, rng)
        score, _ = tokens_to_stream(tokens)
        path = write_midi_file(score, output_dir, f"demo_{index:03d}.mid", overwrite=True)
        created.append(str(path))
    return created


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Create synthetic demo MIDI files in data/raw/.")
    parser.add_argument("--files", type=int, default=12)
    parser.add_argument("--length", type=int, default=240)
    args = parser.parse_args(argv)
    setup_logging()
    try:
        created = create_sample_dataset(files=args.files, length=args.length)
    except MusicGenError as exc:
        print("\n" + exc.describe())
        return 1
    print(f"Created {len(created)} synthetic demo MIDI files in data/raw/.")
    print("Next step: python -m src.preprocessing")
    return 0


if __name__ == "__main__":
    sys.exit(main())
